import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = await import("node:fs/promises").then((fs) =>
  fs.readFile(join(root, "contracts/PerchDegen.sol"), "utf8"),
);

const input = {
  language: "Solidity",
  sources: { "PerchDegenPaperProbe.sol": { content: readFileSync(join(root, "contracts/PerchDegenPaperProbe.sol"), "utf8") }, "PerchDegen.sol": { content: source }, "PerchDegenProbe.sol": { content: readFileSync(join(root, "contracts/PerchDegenProbe.sol"), "utf8") } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input)));
if (out.errors?.some((e) => e.severity === "error")) {
  console.error(out.errors);
  process.exit(1);
}
const art = out.contracts["PerchDegen.sol"].PerchDegen;
const bytecode = `0x${art.evm.bytecode.object}`;
const body = `/* generated by scripts/compile-degen.mjs — do not edit */
export const DEGEN_ABI = ${JSON.stringify(art.abi, null, 2)} as const;

export const DEGEN_BYTECODE = "${bytecode}" as const;
`;
writeFileSync(join(root, "src/lib/degen-artifact.ts"), body);
console.log("wrote src/lib/degen-artifact.ts", bytecode.length, "chars");

const probe = out.contracts["PerchDegenProbe.sol"].PerchDegenProbe;
writeFileSync(join(root, "src/lib/degen-probe-artifact.ts"), `/* generated by scripts/compile-degen.mjs */
export const PROBE_ABI = ${JSON.stringify(probe.abi)} as const;
export const PROBE_BYTECODE = "0x${probe.evm.bytecode.object}" as const;
`);

const paperProbe = out.contracts["PerchDegenPaperProbe.sol"].PerchDegenPaperProbe;
writeFileSync(join(root, "src/lib/degen-paper-probe-artifact.ts"), `/* generated by scripts/compile-degen.mjs */
export const PAPER_PROBE_ABI = ${JSON.stringify(paperProbe.abi)} as const;
export const PAPER_PROBE_BYTECODE = "0x${paperProbe.evm.bytecode.object}" as const;
`);
